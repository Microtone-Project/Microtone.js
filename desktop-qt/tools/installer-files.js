#!/usr/bin/env node
// The Windows installer's file lists (installer/microtone.nsi), made from the
// packaged app folder:
//
//   node desktop-qt/tools/installer-files.js <app folder> <out dir>
//
// writes into <out dir>
//   install-files.nsh    SetOutPath + File for every file, folder by folder,
//                        each File relative to ${STAGE} (the folder, passed to
//                        makensis), and INSTALL_SIZE_KB for Windows' app list
//   uninstall-files.nsh  Delete for every file, then RMDir for every folder,
//                        deepest first — never RMDir /r: someone may have
//                        installed into a folder that holds other things, and
//                        the uninstaller removes what it put there and nothing
//                        else.
//
// Node only, no dependencies (the repository's rule).
import { readdirSync, statSync, writeFileSync, mkdirSync } from "node:fs";
import { join, resolve } from "node:path";

const [stage, out] = process.argv.slice(2);
if (!stage || !out) {
  console.error("usage: node installer-files.js <app folder> <out dir>");
  process.exit(2);
}
const root = resolve(stage);

/** Every folder below the root (relative, "" = the root) with its files. */
function walk(rel, folders) {
  const files = [];
  const subs = [];
  for (const name of readdirSync(join(root, rel)).sort()) {
    const r = rel ? `${rel}/${name}` : name;
    const st = statSync(join(root, r));
    if (st.isDirectory()) subs.push(r);
    else if (st.isFile()) files.push({ rel: r, size: st.size });
  }
  folders.push({ rel, files });
  for (const s of subs) walk(s, folders);
  return folders;
}

const folders = walk("", []);
// Windows names never hold `"`. A path the installer uses at RUN time reads
// `$` as the start of a variable, so it is doubled there; File's source is
// read at COMPILE time, where only `${…}` means anything (a define), and `$`
// stays as it is — a name holding `${` cannot be written at all.
const win = (rel) => rel.replaceAll("/", "\\");
const at = (rel) => (rel ? `$INSTDIR\\${win(rel).replaceAll("$", "$$$$")}` : "$INSTDIR");
const source = (rel) => {
  if (rel.includes("${")) throw new Error(`makensis would read "\${" in ${rel} as a define`);
  return `\${STAGE}\\${win(rel)}`;
};

let bytes = 0;
const install = [
  "; Generated by desktop-qt/tools/installer-files.js — do not edit.",
];
for (const f of folders) {
  if (f.files.length === 0) continue;
  install.push(`SetOutPath "${at(f.rel)}"`);
  for (const file of f.files) {
    install.push(`File "${source(file.rel)}"`);
    bytes += file.size;
  }
}
install.push(`SetOutPath "$INSTDIR"`);
const sizeKb = Math.ceil(bytes / 1024);
install.unshift(`!define INSTALL_SIZE_KB ${sizeKb}`);

const uninstall = [
  "; Generated by desktop-qt/tools/installer-files.js — do not edit.",
];
for (const f of folders) {
  for (const file of f.files) uninstall.push(`Delete "${at(file.rel)}"`);
}
const deepestFirst = folders.map((f) => f.rel).filter((r) => r !== "")
  .sort((a, b) => b.split("/").length - a.split("/").length || (a < b ? 1 : -1));
for (const r of deepestFirst) uninstall.push(`RMDir "${at(r)}"`);

// With a byte-order mark: without one makensis reads a file in the system's
// code page, and a name outside ASCII would come out wrong.
mkdirSync(out, { recursive: true });
const BOM = "\ufeff";
writeFileSync(join(out, "install-files.nsh"), BOM + install.join("\r\n") + "\r\n");
writeFileSync(join(out, "uninstall-files.nsh"), BOM + uninstall.join("\r\n") + "\r\n");
const count = folders.reduce((n, f) => n + f.files.length, 0);
console.log(`${count} files in ${folders.length} folders, ${(bytes / 1048576).toFixed(1)} MB`);
